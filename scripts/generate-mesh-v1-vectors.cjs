#!/usr/bin/env node
// Regenerates tests/fixtures/mesh-v1.json, the device group (mesh v1)
// vectors the backend (Rust) and this package must both pass
// (TodeX_backend docs/mesh-v1.md). Run after `npm run test:unit` compiled
// src/ into dist/unit/lib:
//
//   node scripts/generate-mesh-v1-vectors.cjs
//
// Every key and nonce comes from SHA-256 of a fixed label and Ed25519
// signatures are deterministic, so the output is stable. The backend copies
// the file verbatim to tests/fixtures/mesh-v1.json and verifies it with its
// own implementation.
const fs = require('node:fs');
const path = require('node:path');
const { sha256 } = require('@noble/hashes/sha2.js');
const { ed25519 } = require('@noble/curves/ed25519.js');

const lib = path.join(__dirname, '..', 'dist', 'unit', 'lib');
const mesh = require(path.join(lib, 'mesh.js'));
const { historyRecipientKeyPairFromSeed } = require(path.join(lib, 'historyCrypto.js'));
const { encodeBase64Url } = require(path.join(lib, 'deviceAuth.js'));

const seed = (label) => sha256(new TextEncoder().encode(`todex.mesh.v1/vectors/${label}`));
const hex = (bytes) => Buffer.from(bytes).toString('hex');
const NOW = 1767225600000;

const creatorSecret = seed('creator');
const secondSecret = seed('second');
const nodeSecret = seed('node');
const recoverySeed = seed('recovery');
const strangerSecret = seed('stranger');
const history = (label) => historyRecipientKeyPairFromSeed(seed(`history/${label}`)).publicKey;

const { recovery, signingSeed } = mesh.meshRecoveryKeys(recoverySeed);
const genesis = mesh.createMeshGenesis({
  name: 'Home', creatorSecretKey: creatorSecret, creatorName: 'MacBook',
  creatorHistoryKey: history('creator'), recovery, now: NOW, nonce: seed('nonce').subarray(0, 16),
});
const g = mesh.verifyMeshChain(genesis);
const creator = g.head.members[0];
const node = { ...mesh.meshNodeMember({ publicKey: ed25519.getPublicKey(nodeSecret), name: 'nas', addedBy: creator.id, addedAt: NOW + 1 }), addresses: ['https://nas.example.net:7345'], relay: 'preferred', relayTarget: false };
const second = mesh.meshDeviceMember({ publicKey: ed25519.getPublicKey(secondSecret), name: 'Phone', historyKey: history('second'), addedBy: creator.id, addedAt: NOW + 2 });
const v2 = mesh.appendMeshRoster(g, { signerSecretKey: creatorSecret, members: [creator, node, second], now: NOW + 2 });
const c2 = mesh.verifyMeshChain(v2);
// The second device removes the creator.
const v3 = mesh.appendMeshRoster(c2, { signerSecretKey: secondSecret, members: [node, second], now: NOW + 3 });
const c3 = mesh.verifyMeshChain(v3);
// The recovery key signs the next version and re-adds nobody.
const v4 = mesh.appendMeshRoster(c3, { signerSecretKey: signingSeed, signer: 'recovery', members: [node, second], name: 'Home (recovered)', now: NOW + 4 });
const c4 = mesh.verifyMeshChain(v4);

// Invalid chains, each must be refused.
const strangerMember = mesh.meshDeviceMember({ publicKey: ed25519.getPublicKey(strangerSecret), name: 'Stranger', historyKey: history('stranger'), addedBy: creator.id, addedAt: NOW });
const forgedBody = {
  type: 'todex.mesh.roster', v: 1, groupId: c2.groupId, version: 3, prev: encodeBase64Url(c2.headHash), name: 'Home',
  signer: strangerMember.id, signedAt: NOW + 3, recovery, members: [creator, node, second, strangerMember],
};
const forged = [...v2, mesh.signMeshDoc(mesh.MESH_ROSTER_DOMAIN, forgedBody, strangerSecret)];
// The removed creator signs after its removal.
const removedSigner = [...v3, mesh.signMeshDoc(mesh.MESH_ROSTER_DOMAIN, {
  ...forgedBody, version: 4, prev: encodeBase64Url(c3.headHash), signer: creator.id, members: [creator, node, second],
}, creatorSecret)];
const tampered = v2.map((doc) => ({ ...doc }));
tampered[1] = { ...tampered[1], body: encodeBase64Url(new TextEncoder().encode(Buffer.from(tampered[1].body, 'base64url').toString('utf8').replace('"Phone"', '"Phonf"'))) };
const reordered = [v2[1], v2[0]];

const nodeInfoBody = {
  type: 'todex.mesh.node-info', v: 1, nodeId: node.id, publicKey: node.publicKey, seq: NOW + 10, name: 'nas',
  transportProtocol: 'x25519', transportPublicKey: encodeBase64Url(seed('transport')), urls: ['http://192.168.1.20:7345'], signedAt: NOW + 10,
};
const nodeInfo = mesh.signMeshDoc(mesh.MESH_NODE_INFO_DOMAIN, nodeInfoBody, nodeSecret);

const joinCode = 'abcd-efgh-ijkl-mn01';
const codeKey = mesh.meshJoinCodeKey(joinCode);
const transcriptHash = seed('transcript');

const relayExpiresAt = NOW + 86_400_000;
const relayTicket = mesh.meshRelayTicket({ deviceSecretKey: secondSecret, deviceId: second.id, relayNodeId: node.id, targetNodeId: 'node_AAAAAAAAAAAAAAAA', expiresAt: relayExpiresAt });

const fixture = {
  description: 'mesh v1 vectors (TodeX_backend docs/mesh-v1.md); generated by TodeX_protocol/scripts/generate-mesh-v1-vectors.cjs',
  groupId: c4.groupId,
  chain: v4,
  versions: [g, c2, c3, c4].map((chain) => ({ version: chain.head.version, head: encodeBase64Url(chain.headHash), members: chain.head.members.map((m) => m.id) })),
  memberIds: { creator: creator.id, second: second.id, node: node.id },
  recovery: { seed: hex(recoverySeed), signingKey: recovery.signingKey, historyKey: recovery.historyKey },
  invalidChains: { forged, removedSigner, tampered, reordered, empty: [] },
  nodeInfo: { doc: nodeInfo, publicKey: node.publicKey, body: nodeInfoBody },
  historyKeyBinding: {
    devicePublicKey: second.publicKey, groupId: c4.groupId, historyKey: second.historyKey,
    signature: mesh.meshHistoryKeySignature(secondSecret, c4.groupId, history('second')),
  },
  relayTicket: { ticket: relayTicket, deviceId: second.id, devicePublicKey: second.publicKey, relayNodeId: node.id, targetNodeId: 'node_AAAAAAAAAAAAAAAA', expiresAt: relayExpiresAt },
  joinCode: {
    code: joinCode, normalized: mesh.normalizeMeshJoinCode(joinCode), codeKey: hex(codeKey), transcriptHash: hex(transcriptHash),
    nodePublicKey: node.publicKey,
    clientProof: mesh.meshNodeJoinClientProof(codeKey, transcriptHash),
    serverProof: mesh.meshNodeJoinServerProof(codeKey, transcriptHash, ed25519.getPublicKey(nodeSecret)),
  },
};
const out = path.join(__dirname, '..', 'tests', 'fixtures', 'mesh-v1.json');
fs.writeFileSync(out, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`wrote ${out}`);
